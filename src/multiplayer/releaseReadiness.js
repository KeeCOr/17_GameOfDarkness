function checksForMode(target) {
  return MULTIPLAYER_RELEASE_CHECKS.filter(check => check.modes.includes(target));
}

export function getMMRStorageAssessment() {
  const blocked = MMR_STORAGE_LEVELS.filter(level => level.status === 'blocked');
  return Object.freeze({
    levels: MMR_STORAGE_LEVELS,
    localStorageReady: MMR_STORAGE_LEVELS.some(level => level.id === 'local_server_json' && level.status === 'ready'),
    steamAdapterReady: MMR_STORAGE_LEVELS.some(level => level.id === 'steam_leaderboard_adapter' && level.status === 'adapter-ready'),
    officialRankedReady: blocked.length === 0,
    blockers: Object.freeze(blocked),
  });
}

export function getMultiplayerReleaseAssessment({ target = MULTIPLAYER_RELEASE_MODES.AI_FALLBACK } = {}) {
  const checks = checksForMode(target);
  const blockers = checks.filter(check => !check.passed);
  return Object.freeze({
    target,
    checks: Object.freeze(checks),
    blockers: Object.freeze(blockers),
    complete: blockers.length === 0,
    recommendation: blockers.length === 0
      ? 'Safe for a first Steam release as an AI fallback matchmaking experience.'
      : 'Keep public human PvP ranked mode out of the first release until server-authoritative sync is built.',
    summary: Object.freeze({
      total: checks.length,
      passed: checks.length - blockers.length,
      blocked: blockers.length,
    }),
  });
}
